// Generates src/data/geo.js: projected SVG paths for the journey map.
// Sources: US Census state boundaries (us-atlas) and Natural Earth land (world-atlas).
// India is drawn from coastlines only — no political borders.
// Run: npm run build:geo
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { geoConicEqualArea, geoMercator, geoPath, geoGraticule } from 'd3-geo';
import { feature, merge, mesh } from 'topojson-client';
import { presimplify, simplify, quantile } from 'topojson-simplify';

const require = createRequire(import.meta.url);
const load = (p) => JSON.parse(fs.readFileSync(require.resolve(p)));
const round = (d) => d.replace(/\d+\.\d+/g, (n) => (+n).toFixed(1));

let states = presimplify(load('us-atlas/states-10m.json'));
states = simplify(states, quantile(states, 0.06));
const outside48 = new Set(['02', '15', '60', '66', '69', '72', '78']);
const lower48 = states.objects.states.geometries.filter((g) => !outside48.has(g.id));
const usOutline = merge(states, lower48);
const usInner = mesh(states, { type: 'GeometryCollection', geometries: lower48 }, (a, b) => a !== b);
const usProj = geoConicEqualArea().parallels([29.5, 45.5]).rotate([96, 0]).fitExtent([[30, 92], [560, 418]], usOutline);

let land = presimplify(load('world-atlas/land-50m.json'));
land = simplify(land, quantile(land, 0.08));
const IN_BOX = [[655, 70], [985, 420]];
// Clockwise ring (d3 spherical winding) around India's extent.
const indiaExtent = { type: 'Polygon', coordinates: [[[68, 6.5], [68, 35.5], [97.5, 35.5], [97.5, 6.5], [68, 6.5]]] };
const inProj = geoMercator().fitExtent(IN_BOX, indiaExtent).clipExtent([[615, 30], [1000, 430]]);

const us = geoPath(usProj);
const ind = geoPath(inProj);
const geo = {
  usOutline: round(us(usOutline)),
  usInner: round(us(usInner)),
  usGraticule: round(us(geoGraticule().step([5, 5]).extent([[-130, 22], [-62, 52]])())),
  indiaLand: round(ind(feature(land, land.objects.land))),
  indiaGraticule: round(ind(geoGraticule().step([5, 5]).extent([[60, 0], [105, 42]])())),
  cities: Object.fromEntries(
    Object.entries({
      JAI: [inProj, 75.79, 26.91], DEL: [inProj, 77.21, 28.61],
      CHO: [usProj, -78.48, 38.03], FNL: [usProj, -105.08, 40.59], CHI: [usProj, -87.63, 41.88], CLE: [usProj, -81.69, 41.5],
    }).map(([k, [p, lon, lat]]) => [k, p([lon, lat]).map((n) => +n.toFixed(1))])
  ),
};
fs.writeFileSync(
  new URL('../src/data/geo.js', import.meta.url),
  `// Generated by scripts/build-geo.mjs — do not edit by hand.\nexport const GEO = ${JSON.stringify(geo)};\n`
);
console.log('wrote src/data/geo.js', geo.cities);
